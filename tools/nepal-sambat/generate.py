"""Generates the Nepal Sambat tables for the .NET and JS packages.

    pip install ephem
    python tools/nepal-sambat/generate.py

Writes src/OSN.NepaliCalendar/NepalSambatData.cs and js/packages/core/src/nepal-sambat-data.ts.
A JS test checks that the two stay identical.
"""
import datetime
import os
import textwrap

import compute

STEP_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZa'  # 27 symbols: three days of steps (0, 1 or 2) per symbol
# Hamro Patro shows BS 2083-07-24 (AD 2026-11-10) as NS 1147 Kachhalā Thwa Pāru (Mha Puja).
YEAR_ANCHOR = (datetime.date(2026, 11, 10), 1147)


def encode():
    days, months = compute.compute()
    tithis = [t for _, t in days]
    steps = [(tithis[i] - tithis[i - 1]) % 30 for i in range(1, len(tithis))]
    assert set(steps) <= {0, 1, 2}, set(steps)
    while len(steps) % 3:
        steps.append(1)
    step_text = ''.join(STEP_ALPHABET[steps[i] * 9 + steps[i + 1] * 3 + steps[i + 2]] for i in range(0, len(steps), 3))
    month_text = ''.join((chr(ord('A') + m['month'] - 1) if m['leap'] else chr(ord('a') + m['month'] - 1)) for m in months)

    # NS year of each lunar month, counting back from the anchor. The year turns over at the first
    # ordinary (non-leap) month whose number is lower than the previous ordinary month's.
    years = [0]
    last = None
    for m in months:
        if not m['leap'] and last is not None and m['month'] < last:
            years.append(years[-1] + 1)
        else:
            years.append(years[-1])
        if not m['leap']:
            last = m['month']
    years = years[1:]
    anchor_index = next(i for i, (d, _) in enumerate(days) if d == YEAR_ANCHOR[0])
    anchor_month = max(k for k, m in enumerate(months) if m['start_index'] <= anchor_index)
    first_year = YEAR_ANCHOR[1] - years[anchor_month]
    return {'first_date': days[0][0], 'first_tithi': tithis[0], 'first_year': first_year,
            'steps': step_text, 'months': month_text, 'day_count': len(days)}


def chunks(text, width=100):
    return [text[i:i + width] for i in range(0, len(text), width)]


def write_cs(data, path):
    steps = '\n'.join(f'        "{c}" +' for c in chunks(data['steps']))[:-2] + ';'
    months = '\n'.join(f'        "{c}" +' for c in chunks(data['months']))[:-2] + ';'
    text = f'''// <auto-generated>
// Generated by tools/nepal-sambat/generate.py. Do not edit by hand.
// </auto-generated>

namespace OSN.NepaliCalendar;

/// <summary>Encoded Nepal Sambat data for every day from BS 1970-01-01 to the end of BS 2090.</summary>
internal static partial class NepalSambatData
{{
    /// <summary>Number of days covered, the same as the BS calendar data.</summary>
    internal const int DayCount = {data['day_count']};

    /// <summary>Tithi (1-30) on the first day, BS 1970-01-01 ({data['first_date'].isoformat()}).</summary>
    internal const int FirstTithi = {data['first_tithi']};

    /// <summary>NS year of the lunar month that contains the first day.</summary>
    internal const int FirstYear = {data['first_year']};

    /// <summary>
    /// How far the tithi moves from one day to the next (0 = repeated, 1, 2 = one skipped), three days per
    /// character of <c>{STEP_ALPHABET}</c> (first day of the three times 9, plus second times 3, plus third).
    /// </summary>
    internal const string Steps =
{steps}

    /// <summary>One character per lunar month: a-l for Kachhala to Kaula, A-L for a leap month (Anala) of that name.</summary>
    internal const string Months =
{months}
}}
'''
    open(path, 'w', newline='\n').write(text)


def write_ts(data, path):
    steps = '\n'.join(f"    '{c}'," for c in chunks(data['steps']))
    months = '\n'.join(f"    '{c}'," for c in chunks(data['months']))
    text = f'''// Generated by tools/nepal-sambat/generate.py. Do not edit by hand. A test checks it matches NepalSambatData.cs.

/** Number of days covered, the same as the BS calendar data. */
export const NS_DAY_COUNT = {data['day_count']};

/** Tithi (1-30) on the first day, BS 1970-01-01 ({data['first_date'].isoformat()}). */
export const NS_FIRST_TITHI = {data['first_tithi']};

/** NS year of the lunar month that contains the first day. */
export const NS_FIRST_YEAR = {data['first_year']};

/**
 * How far the tithi moves from one day to the next (0 = repeated, 1, 2 = one skipped), three days per
 * character of `{STEP_ALPHABET}` (first day of the three times 9, plus second times 3, plus third).
 */
export const NS_STEPS = [
{steps}
].join('');

/** One character per lunar month: a-l for Kachhala to Kaula, A-L for a leap month (Anala) of that name. */
export const NS_MONTHS = [
{months}
].join('');
'''
    open(path, 'w', newline='\n').write(text)


if __name__ == '__main__':
    data = encode()
    write_cs(data, os.path.join(compute.ROOT, 'src', 'OSN.NepaliCalendar', 'NepalSambatData.cs'))
    write_ts(data, os.path.join(compute.ROOT, 'js', 'packages', 'core', 'src', 'nepal-sambat-data.ts'))
    print('first year', data['first_year'], 'steps', len(data['steps']), 'months', len(data['months']))
