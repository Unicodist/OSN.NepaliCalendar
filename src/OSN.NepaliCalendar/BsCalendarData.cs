    /// <summary>Days from <see cref="Anchor"/> to the first day of each year, plus one trailing total.</summary>
    private static readonly int[] _yearStarts = BuildYearStarts();

    /// <summary>Gets the number of days in the supported range.</summary>
    internal static int TotalDays => _yearStarts[_yearStarts.Length - 1];

    /// <summary>Gets the Gregorian date of the last supported day.</summary>
    internal static DateTime MaxGregorian => Anchor.AddDays(TotalDays - 1);

    /// <summary>Returns whether <paramref name="year"/> is within the supported range.</summary>
    internal static bool IsSupportedYear(int year) => year >= MinYear && year <= MaxYear;

    /// <summary>Returns the number of days in a month. The year and month must already be validated.</summary>
    internal static int DaysInMonth(int year, int month) => _monthLengths[year - MinYear][month - 1];

    /// <summary>Returns the number of days from <see cref="Anchor"/> to the given validated date.</summary>
    internal static int ToDayNumber(int year, int month, int day)
    {
        var dayNumber = _yearStarts[year - MinYear];
        for (var m = 1; m < month; m++)
        {
            dayNumber += DaysInMonth(year, m);
        }

        return dayNumber + day - 1;
    }

    /// <summary>Returns the BS date that lies <paramref name="dayNumber"/> days after <see cref="Anchor"/>.</summary>
    internal static NepaliDate FromDayNumber(int dayNumber)
    {
        // The largest year whose start is not after dayNumber.
        var index = Array.BinarySearch(_yearStarts, dayNumber);
        if (index < 0)
        {
            index = ~index - 1;
        }

        var year = MinYear + index;
        var remaining = dayNumber - _yearStarts[index];
        var month = 1;
        while (remaining >= DaysInMonth(year, month))
        {
            remaining -= DaysInMonth(year, month);
            month++;
        }

        return new NepaliDate(year, month, remaining + 1);
    }

    private static int[] BuildYearStarts()
    {
        var starts = new int[_monthLengths.Length + 1];
        for (var i = 0; i < _monthLengths.Length; i++)
        {
            var yearLength = 0;
            foreach (var monthLength in _monthLengths[i])
            {
                yearLength += monthLength;
            }

            starts[i + 1] = starts[i] + yearLength;
        }

        return starts;
    }
