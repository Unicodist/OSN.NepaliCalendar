namespace OSN.NepaliCalendar;

/// <summary>
/// Months of the Nepali (Bikram Sambat) calendar.
/// </summary>
public enum NepaliMonth
{
    /// <summary>बैशाख, the first month.</summary>
    Baisakh = 1,

    /// <summary>जेठ, the second month.</summary>
    Jestha = 2,

    /// <summary>असार, the third month.</summary>
    Ashadh = 3,

    /// <summary>साउन, the fourth month.</summary>
    Shrawan = 4,

    /// <summary>भदौ, the fifth month.</summary>
    Bhadra = 5,

    /// <summary>असोज, the sixth month.</summary>
    Ashwin = 6,

    /// <summary>कात्तिक, the seventh month.</summary>
    Kartik = 7,

    /// <summary>मंसिर, the eighth month.</summary>
    Mangsir = 8,

    /// <summary>पुस, the ninth month.</summary>
    Poush = 9,

    /// <summary>माघ, the tenth month.</summary>
    Magh = 10,

    /// <summary>फागुन, the eleventh month.</summary>
    Falgun = 11,

    /// <summary>चैत, the twelfth month.</summary>
    Chaitra = 12,
}
