namespace OSN.NepaliCalendar;

/// <summary>
/// The two halves (fortnights) of a lunar month.
/// </summary>
public enum Paksha
{
    /// <summary>थ्व (shukla), the bright half: from the day after the new moon to the full moon.</summary>
    Thwa = 0,

    /// <summary>गा (krishna), the dark half: from the day after the full moon to the new moon.</summary>
    Ga = 1,
}
